// Builds data/board-geometry.json from TripleA's classic map geometry
// (data/source/triplea-centers.txt + triplea-polygons.txt + map.properties,
// https://github.com/triplea-maps/world_war_ii_classic). Same territory names
// as the game XML, so ids line up with data/territories.json.
// Polygons are decimated (Douglas-Peucker) to keep the bundle small.
// Run: node scripts/build-geometry.mjs — never hand-edit the output.
import { readFileSync, writeFileSync } from 'node:fs';

const id = (name) =>
  name.toLowerCase().replace(/['.]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const read = (f) => readFileSync(new URL(`../data/source/${f}`, import.meta.url), 'utf8');
const knownIds = new Set(
  JSON.parse(readFileSync(new URL('../data/territories.json', import.meta.url), 'utf8'))
    .territories.map((t) => t.id),
);

// --- map size ---
const props = read('triplea-map.properties');
const width = Number(props.match(/map\.width\s*=\s*(\d+)/)[1]);
const height = Number(props.match(/map\.height\s*=\s*(\d+)/)[1]);

// --- centers ---
const centers = {};
for (const line of read('triplea-centers.txt').split(/\r?\n/)) {
  const m = line.match(/^(.+?)\s+\((\d+),(\d+)\)\s*$/);
  if (!m) continue;
  centers[id(m[1])] = [Number(m[2]), Number(m[3])];
}

// --- polygons (Name  < (x,y) (x,y) ... >  < ... > ) ---
function simplify(pts, tol) {
  // iterative Douglas-Peucker
  if (pts.length <= 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let maxD = 0, maxI = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len;
      if (d > maxD) { maxD = d; maxI = i; }
    }
    if (maxD > tol && maxI > 0) {
      keep[maxI] = 1;
      stack.push([a, maxI], [maxI, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const polygons = {};
const polyText = read('triplea-polygons.txt');
for (const line of polyText.split(/\r?\n/)) {
  const m = line.match(/^(.+?)\s+<(.*)$/);
  if (!m) continue;
  const tid = id(m[1]);
  const polys = [];
  for (const seg of line.matchAll(/<([^>]*)>/g)) {
    const pts = [...seg[1].matchAll(/\((\d+),(\d+)\)/g)].map((p) => [Number(p[1]), Number(p[2])]);
    if (pts.length >= 3) polys.push(simplify(pts, 2.5));
  }
  if (polys.length) polygons[tid] = polys;
}

// --- merge + sanity ---
const out = { _provenance: 'generated by scripts/build-geometry.mjs from TripleA classic map files — do not hand-edit', width, height, territories: {} };
const missing = [];
for (const tid of knownIds) {
  const c = centers[tid];
  const p = polygons[tid];
  if (!c || !p) { missing.push(tid); continue; }
  out.territories[tid] = { center: c, polygons: p };
}
const extra = Object.keys(polygons).filter((t) => !knownIds.has(t));
if (missing.length) throw new Error(`geometry missing for: ${missing.join(', ')}`);
if (extra.length) console.warn('geometry for unknown territories (ignored):', extra.join(', '));

writeFileSync(new URL('../data/board-geometry.json', import.meta.url), JSON.stringify(out));
const totalPts = Object.values(out.territories).reduce((s, t) => s + t.polygons.reduce((a, p) => a + p.length, 0), 0);
console.log(`geometry: ${Object.keys(out.territories).length} territories, ${totalPts} points, ${(JSON.stringify(out).length / 1024).toFixed(0)}kB`);
